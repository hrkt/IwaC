/* 文字列を fd に書く (長さは自分で数える) */
static void print_str(int fd, char *s) {
    long len = 0;
    while (s[len] != '\0')
        len++;
    write(fd, s, len);
}

/* 1バイトを標準出力 (fd = 1) に書く。第3層だけが使う */
static void out_byte(int byte) {
    char b = (char)byte;
    write(1, &b, 1);
}


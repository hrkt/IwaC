/* iwac -- Cコンパイラのサブセット (v1)
 *
 * v1 で育ったこと: 「式」が書けるようになった。
 * 数字と + / - だけの式を受け取り、実行時に計算して、結果の
 * 一番下の1バイトを UART に出して止まる RISC-V (rv64i) の
 * 生バイナリを、標準出力に書き出す。
 *
 * === v1 の言語 (文法) ===
 *
 *   program = 1文字               (v0 との互換。その文字コードが値)
 *           | expr
 *   expr    = number { ("+" | "-" ) number }
 *   number  = 数字の並び (10進数、0..2047。理由は後述)
 *
 *   例: "65+1"  → 66 が値になり、'B' が出る
 *       "66-1"  → 65 が値になり、'A' が出る
 *       " 65 + 1 " のように空白を挟んでもよい
 *   シェルでは + などの記号をそのまま引数に混ぜるため、
 *   実行するときは './iwac '65+1'' のように引用符で囲むこと。
 *
 * === 大事な考え方: 計算は「実行時に」させる ===
 *
 * iwac 自身が 65+1 を計算して 66 を埋め込むこともできるが、
 * それはコンパイラの仕事ではない (それは計算機の仕事)。
 * コンパイラの仕事は「計算する命令の並び」を作ること。
 * なので v1 が出すバイナリの中では、本物の add / sub 命令が
 * 実行時にレジスタ同士を計算する。この区別が v1 の核心。
 *
 * === ファイルの構成 (3段構えへの第一歩) ===
 *
 *   - 字句・構文解析 (parse): 入力文字列を読んで、項 (数字) の
 *     配列 terms[] と、演算子の配列 ops[] に分解する。
 *     読み終わるまで機械語は1バイトも出さない。途中で文法
 *     エラーが見つかれば、何も出力せずにエラーで終わる
 *     (半端なバイナリをファイルに残さないため)。
 *   - コード生成 (codegen): terms[] / ops[] を機械語に変える。
 *     レジスタの約束 (設計書 doc/design.md):
 *       t0 (x5) = UART ベースアドレス 0x10000000 専用
 *       t1 (x6) = 今の値 (最初の項を入れ、演算のたびに更新)
 *       t2 (x7) = 次の項 (演算の相手)
 *     生成の形は項の数だけ繰り返す:
 *       lui   t0, 0x10000        -- 土台 (最初に1回)
 *       addi  t1, zero, 項0      -- 今の値 = 最初の項
 *       addi  t2, zero, 項1      -- 次の項
 *       add   t1, t1, t2         -- 今の値 += 次の項 (- なら sub)
 *       ... 項の数だけ繰り返し ...
 *       sb    t1, 0(t0)          -- 結果の下1バイトを UART へ
 *       wfi                      -- 止まる
 *
 * === 数字の上限が 2047 なのはなぜか ===
 *
 * 項をレジスタに入れる addi 命令は、即値 (命令の中に直接
 * 埋め込む数) が12ビットしかなく、しかも符号付きで解釈される。
 * 正の数は 0..2047 まで。2048 以上は負の数になってしまう。
 * 大きな数を入れる方法 (lui と組み合わせる) は後のステップの
 * 題材として、v1 では上限を超えたらエラーを出す。
 * ただし「計算の途中経過や結果」はレジスタ (64ビット) の中
 * での出来事なので、この上限はない。最後に sb が下1バイト
 * だけを UART に出す (例: "2000+2000" の結果は 4000 で、
 * UART に出るのは 4000 の下1バイト = 0xA0)。
 *
 * === 混同しやすい「2つの出力」 (v0 から引き続き) ===
 *
 *   - iwac 自身の出力先は「ホストの標準出力」。このファイルの
 *     out_byte 関数が、命令のバイト列を標準出力に書いている。
 *   - 作られたバイナリの出力先は「ベアメタル機の UART」。
 *     バイナリの中の sb 命令が UART のレジスタに書く。
 *
 * === なぜこのファイルに #include が無いのか ===
 *
 * iwac の言語にはプリプロセッサが無いと決めた。なのに iwac
 * 自身のソースが #include <stdio.h> を使っていたら、「まだ
 * 作っていないもの」を使って作っていることになってしまう。
 * 将来のセルフホストの妨げにもなる。そこでこのファイルは
 * プリプロセッサ (#include も #define も) を一切使わない。
 *
 * では標準ライブラリの関数はどうするか。使うのは write だけ
 * とし、その「宣言」だけを自分で書く:
 *
 *   long write(int fd, char *buf, long len);
 *
 * 宣言はプリプロセッサではなく、「こういう形の関数が外に
 * ある」というコンパイラへの伝言。本体はホストのライブラリ
 * にあり、リンクのときに繋がる。将来 iwac でプログラムを
 * 書くときも、#include の代わりに使う関数の宣言を自分で
 * 書く想定でいる (Hello World の書き方もこの流儀になる)。
 * エラー表示も write で標準エラー出力 (fd = 2) に書く。
 */

/* 外部関数の宣言 (ヘッダの代わりに自分で書く。上の説明参照)
 * write: fd へ buf の先頭 len バイトを書くホストの関数。
 * 戻り値は実際に書けたバイト数だが、このプログラムでは使わない。 */
long write(int fd, char *buf, long len);

/* ----------------------------------------------------------------
 * ホストへの入出力 (iwac 自身が使う側)
 * ---------------------------------------------------------------- */

/* 文字列を fd に書く (長さは自分で数える。ライブラリ関数の
 * strlen も使わない方針) */
static void print_str(int fd, char *s) {
    long len = 0;
    while (s[len] != '\0')
        len++;
    write(fd, s, len);
}

/* 1バイトを標準出力 (fd = 1) に書く。emit32 から呼ばれる。
 * ここが「iwac の出力」と「作られるバイナリの出力」の境目:
 * 書かれたバイトは、シェルのリダイレクトで .bin ファイルになる。 */
static void out_byte(int byte) {
    char b = (char)byte;
    write(1, &b, 1);
}

/* ----------------------------------------------------------------
 * エラー処理
 *
 * 方針: エラーが起きた関数は「失敗」を戻り値で伝え、理由を
 * errmsg に置く。main が最後にまとめて表示して終わる。
 * exit() のようなライブラリ関数に頼らずに済ませるためと、
 * 「どこで失敗したか」を main に集約するため。
 * 解析の途中で失敗しても、機械語はまだ何も出力されていない
 * ので、「変なバイナリが黙って出来てしまう」ことがない。
 * ---------------------------------------------------------------- */

static char *errmsg;  /* 失敗の理由。成功している間は使わない */

/* ----------------------------------------------------------------
 * 字句・構文解析 (parse)
 *
 * 入力文字列を左から読むカーソル cur を使いながら、
 * 項と演算子を取り出して配列に溜めるのがこの段の仕事。
 * ---------------------------------------------------------------- */

static char *cur;         /* 入力の「今読んでいる場所」 */
/* 項の数の上限は 256 (#define のようなプリプロセッサは
 * 使わない方針なので、数は配列とチェックに直接書く) */
static int terms[256];    /* 項 (数字) の配列 */
static char ops[256];     /* ops[i] = terms[i] と terms[i+1] の間の演算子 */
static int nterms;        /* 溜まった項の数 */

static int is_digit(char c) {
    return c >= '0' && c <= '9';
}

/* 空白は意味を持たないので読み飛ばす (字句解析の典型的な仕事) */
static void skip_spaces(void) {
    while (*cur == ' ' || *cur == '\t')
        cur++;
}

/* カーソルの位置から数字を1つ読み、値を返す。読み終えたら
 * カーソルは数字の直後まで進む。これが「数トークン」を
 * 取り出す処理にあたる (v0 の手読みを関数に独立させた)。
 * 失敗したら -1 を返し、理由を errmsg に置く (数字は必ず
 * 0 以上なので、-1 を「失敗の合図」に使える)。 */
static int parse_number(void) {
    if (!is_digit(*cur)) {
        errmsg = "数字が必要です";
        return -1;
    }
    int value = 0;
    while (is_digit(*cur)) {
        value = value * 10 + (*cur - '0');
        if (value > 2047) {
            errmsg = "項が大きすぎます (v1 では 2047 まで。addi の即値が12ビットのため)";
            return -1;
        }
        cur++;
    }
    return value;
}

/* プログラム全体を解析して terms[] / ops[] に溜める。
 * 成功したら 1、失敗したら 0 を返す (理由は errmsg)。 */
static int parse(char *program) {
    cur = program;
    nterms = 0;

    skip_spaces();

    /* v0 互換: プログラムが丸ごと1文字 (数字以外) なら、
     * その文字コードを唯一の項として扱う */
    if (cur[0] != '\0' && cur[1] == '\0' && !is_digit(cur[0])) {
        terms[0] = (unsigned char)cur[0];
        nterms = 1;
        return 1;
    }

    /* 式: 最初の項は必須 */
    int first = parse_number();
    if (first < 0)
        return 0;
    terms[nterms++] = first;

    /* その後は (演算子 項) の繰り返し */
    for (;;) {
        skip_spaces();
        if (*cur == '\0')
            break;  /* 式の終わり。正常終了 */
        if (*cur != '+' && *cur != '-') {
            errmsg = "演算子は + か - だけです (他の記号はまだ未対応)";
            return 0;
        }
        if (nterms >= 256) {
            errmsg = "項が多すぎます";
            return 0;
        }
        ops[nterms - 1] = *cur;
        cur++;
        skip_spaces();
        int next = parse_number();
        if (next < 0)
            return 0;
        terms[nterms++] = next;
    }
    return 1;
}

/* ----------------------------------------------------------------
 * コード生成 (codegen)
 * ---------------------------------------------------------------- */

/* 32ビットの命令を、バイナリとしてリトルエンディアンで出す。
 * (小さい方のバイトから順に書くのがリトルエンディアン) */
static void emit32(unsigned int inst) {
    out_byte(inst & 0xff);
    out_byte((inst >> 8) & 0xff);
    out_byte((inst >> 16) & 0xff);
    out_byte((inst >> 24) & 0xff);
}

/* addi rd, zero, imm -- 「レジスタ rd に小さい数 imm を入れる」
 * I形式: [ imm (12ビット) << 20 | rs1 = 0 (zero) | funct3 = 0
 *         | rd << 7 | opcode 0x13 ]
 * rs1 が zero レジスタ (常に0) なので、0 + imm = imm になる。 */
static void emit_addi(int rd, int imm) {
    emit32(((unsigned int)imm << 20) | ((unsigned int)rd << 7) | 0x13u);
}

/* add t1, t1, t2 -- 「今の値 t1 = t1 + t2」
 * R形式 (レジスタ同士の演算): [ funct7 = 0 | rs2 << 20
 *   | rs1 << 15 | funct3 = 0 | rd << 7 | opcode 0x33 ]
 * rs2 = 7 (t2), rs1 = 6 (t1), rd = 6 (t1) を代入すると
 * 0x00730333 になる。 */
static void emit_add_t1_t2(void) {
    emit32(0x00730333u);
}

/* sub t1, t1, t2 -- 「今の値 t1 = t1 - t2」
 * add との違いは funct7 が 0x20 になることだけ
 * (funct7 = 0x20 << 25 = 0x40000000)。 */
static void emit_sub_t1_t2(void) {
    emit32(0x40730333u);
}

/* terms[] / ops[] から機械語列を生成する */
static void codegen(void) {
    /* lui t0, 0x10000 -- UART ベース 0x10000000 を作る (v0 と同じ)
     * 形式: imm[31:12] | rd(5) | opcode 0x37 */
    emit32(0x100002b7u);

    /* 最初の項を「今の値」t1 へ */
    emit_addi(6, terms[0]);  /* addi t1, zero, terms[0] */

    /* 残りの項を、演算子に従って1つずつ重ねる */
    for (int i = 1; i < nterms; i++) {
        emit_addi(7, terms[i]);  /* addi t2, zero, terms[i] */
        if (ops[i - 1] == '+')
            emit_add_t1_t2();
        else
            emit_sub_t1_t2();
    }

    /* sb t1, 0(t0) -- 結果の下1バイトを UART 送信レジスタへ (v0 と同じ)
     * 形式: rs2(6) << 20 | rs1(5) << 15 | funct3(0) | opcode 0x23 */
    emit32(0x00628023u);

    /* wfi -- 止まる (v0 と同じ固定パターン) */
    emit32(0x10500073u);
}

/* ----------------------------------------------------------------
 * 入口: 解析してから生成する (この順序が重要。設計書参照)
 * ---------------------------------------------------------------- */

int main(int argc, char **argv) {
    if (argc != 2) {
        print_str(2, "usage: iwac '<式>'   例: iwac '65+1'\n");
        return 1;
    }

    /* 全部読み終わるまで何も出力しない。失敗したら理由を
     * 標準エラー出力 (fd = 2) に出して、1 で終わる
     * (バイナリ側の標準出力には何も出ていない) */
    if (!parse(argv[1])) {
        print_str(2, "iwac: ");
        print_str(2, errmsg);
        print_str(2, "\n");
        return 1;
    }
    codegen();        /* 読めたものだけを機械語にする */
    return 0;
}

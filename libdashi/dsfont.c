/* 文字 c の字形 (5 バイト) へのポインタを返す。
 * 印字可能 ASCII の範囲外は空白 (全部 0) を指す */
char *ds_glyph(int c) {
    if (c < 32 || c > 126)
        return ds_font5x7;
    return ds_font5x7 + (c - 32) * 5;
}

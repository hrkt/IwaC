/* 文字 c の字形 (5 バイト) へのポインタを返す。
 * 表に無い文字は blank (全部 0) を指す */
char *ds_glyph(int c) {
    int i;
    i = 43;
    if (c >= 'A' && c <= 'Z') {
        i = c - 'A';
    } else if (c >= '0' && c <= '9') {
        i = 26 + (c - '0');
    } else if (c == '!') {
        i = 36;
    } else if (c == '+') {
        i = 37;
    } else if (c == '-') {
        i = 38;
    } else if (c == '.') {
        i = 39;
    } else if (c == ':') {
        i = 40;
    } else if (c == '/') {
        i = 41;
    } else if (c == '>') {
        i = 42;
    }
    return ds_font5x7 + i * 5;
}
